updated = 0
for fp in sorted(glob.glob('blog/*/index.html')):
    slug = fp.replace(os.sep, '/').split('/')[1]

    with open(fp, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content

    # 1. Improve lead text
    if slug in leads:
        # Find first <p> after closing </h1> (skip banners/notices)
        # Look for pattern: </h1> ... <p>old lead</p>
        pattern = r'(</h1>\s*(?:<div[^>]*class="[^"]*banner[^"]*"[^>]*>.*?</div>\s*)?)<p(?:\s[^>]*)?>(.*?)</p>'
        match = re.search(pattern, content, re.DOTALL)
        if match:
            old_p_start = match.start() + len(match.group(1))
            old_p_end = match.end()
            new_p = '<p class="blog-lead">' + leads[slug] + '</p>'
            content = content[:old_p_start] + new_p + content[old_p_end:]

    # 2. Add professional insight section
    if slug in pro_sections:
        title, text = pro_sections[slug]
        # Check if already added
        if title not in content:
            # Insert before CTA section or before footer
            cta_match = re.search(r'(<section[^>]*class="[^"]*cta)', content)
            if not cta_match:
                cta_match = re.search(r'(<footer)', content)
            if cta_match:
                pro_html = (
                    '\n      <section style="background:var(--bg-alt);padding:48px 0;">\n'
                    '        <div class="container">\n'
                    '          <h3 style="font-family:\'Noto Serif JP\',serif;font-size:1.2rem;color:var(--main);margin-bottom:16px;">'
                    + title + '</h3>\n'
                    '          <p style="line-height:2;color:var(--text);">'
                    + text + '</p>\n'
                    '        </div>\n'
                    '      </section>\n\n      '
                )
                pos = cta_match.start()
                content = content[:pos] + pro_html + content[pos:]

    if content != original:
        with open(fp, 'w', encoding='utf-8') as f:
            f.write(content)
        updated += 1
        print(f"Updated: {slug}")

print(f"\nTotal updated: {updated} articles")
